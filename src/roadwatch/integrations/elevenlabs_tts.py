"""User-triggered audio narration of EXISTING evidence via the ElevenLabs text-to-speech REST API.

Endpoint (official docs): POST https://api.elevenlabs.io/v1/text-to-speech/{voice_id}?output_format=mp3_44100_128,
header `xi-api-key`, JSON body {"text", "model_id"}; the 200 response body is the audio file.
The narration text is built from tool-verified evidence (street name, ZIP, report counts, rank, road attributes). It never
includes raw 311 records or complaint text. Audio is generated only when asked for and cached on disk by content hash.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import requests

from . import config

URL = "https://api.elevenlabs.io/v1/text-to-speech/{voice_id}"
DEFAULT_VOICE = "JBFqnCBsd6RMkjVDRZzb"          # voice id used in ElevenLabs' API reference example; override with ELEVENLABS_VOICE_ID
DEFAULT_MODEL = "eleven_multilingual_v2"         # documented default model_id; override with ELEVENLABS_MODEL_ID
MAX_CHARS = 900
TIMEOUT_S = 30
CACHE_DIR = config.ROOT / "outputs" / "integrations" / "audio_cache"
DISCLAIMER = ("This narration reads out existing RoadWatch evidence. It is not an independent prediction, and it does not "
              "confirm a road defect.")


def block_narration(ev: dict) -> str:
    """Short text from a get_block_evidence result's `data`. Plain, factual, no new numbers."""
    if not ev.get("on_worklist"):
        return (f"Block {ev['block_id']} is not on this week's worklist. It ranks {ev['within_week_rank_of_all_blocks']} "
                f"of {ev['blocks_ranked']} blocks. {DISCLAIMER}")
    lanes = f", {ev['travel_lanes']:.0f} travel lanes" if ev.get("travel_lanes") else ""
    return (f"Rank {ev['rank']}: {ev['street']}, ZIP {ev['zip']}, priority {ev['priority']} for the week of {ev['week']}. "
            f"{ev['reports_365d']} 311 pothole reports named this block or its end intersections in the past year, "
            f"{ev['reports_30d']} of them in the last 30 days. The block is {ev['length_m']} metres long{lanes}. "
            f"Recommended action: inspect; this is not a repair order. {DISCLAIMER}")


def worklist_narration(pos: dict) -> str:
    top = pos["top"][:5]
    items = "; ".join(f"number {t['rank']}, {t['street']}, ZIP {t['zip']}" for t in top)
    return (f"The top {len(top)} of {pos['of']} blocks on the {pos['capacity']} worklist for the week of {pos['week']} are: {items}. "
            f"Scores are rankings, not probabilities. {DISCLAIMER}")


def cache_path(text: str, voice: str, model: str) -> Path:
    h = hashlib.sha256(f"{voice}|{model}|{text}".encode("utf-8")).hexdigest()[:32]
    return CACHE_DIR / f"{h}.mp3"


class Narrator:
    def __init__(self, post=None, cache_dir: Path | None = None):
        self._post = post or requests.post
        self.cache_dir = cache_dir or CACHE_DIR
        self.api_calls = 0

    @property
    def remote_enabled(self) -> bool:
        return config.flag("elevenlabs") and not config.missing_credentials("elevenlabs")

    def synthesize(self, text: str) -> tuple[bytes | None, str]:
        """Return (mp3 bytes or None, message). Never raises; the text equivalent is always available to the caller."""
        text = " ".join(text.split())
        if len(text) > MAX_CHARS:
            return None, f"Narration is limited to {MAX_CHARS} characters."
        if not self.remote_enabled:
            why = "ElevenLabs is disabled" if not config.flag("elevenlabs") else "ELEVENLABS_API_KEY is missing"
            return None, f"{why}; read the text instead."
        import os
        voice = os.environ.get("ELEVENLABS_VOICE_ID", DEFAULT_VOICE)
        model = os.environ.get("ELEVENLABS_MODEL_ID", DEFAULT_MODEL)
        p = self.cache_dir / cache_path(text, voice, model).name
        if p.exists():
            return p.read_bytes(), "Played from cache (no API call)."
        try:
            self.api_calls += 1
            r = self._post(URL.format(voice_id=voice), params={"output_format": "mp3_44100_128"}, timeout=TIMEOUT_S,
                           headers={"xi-api-key": config.secret("ELEVENLABS_API_KEY"), "Content-Type": "application/json"},
                           json={"text": text, "model_id": model})
        except requests.RequestException as e:
            return None, f"Audio unavailable ({type(e).__name__}); read the text instead."
        if r.status_code != 200 or not r.content:
            return None, f"ElevenLabs returned HTTP {r.status_code}; read the text instead."
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        p.write_bytes(r.content)
        return r.content, "Generated by ElevenLabs and cached."
